async function listSourceFiles(dir: string): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listSourceFiles(full)));
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      files.push(full);
    }
  }
  return files;
}

describe('absence: no MCP JSON/TOML syntax literal outside the two shared serializer modules', () => {
  it('no generator file and not src/mcp.ts contains a "[mcp_servers." table-header literal', async () => {
    const candidateDirs = [path.join(REPO_ROOT, 'src', 'generators'), path.join(REPO_ROOT, 'src')];
    const seen = new Set<string>();
    const files: string[] = [];
    for (const dir of candidateDirs) {
      for (const file of await listSourceFiles(dir)) {
        if (seen.has(file)) continue;
        seen.add(file);
        files.push(file);
      }
    }

    for (const file of files) {
      if (path.basename(file) === 'toml.ts' && path.dirname(file).endsWith('generators')) continue; // the one legitimate home
      const contents = await fs.readFile(file, 'utf8');
      expect(contents, `${file} contains a hand-rolled [mcp_servers. literal`).not.toContain('[mcp_servers.');
    }
  });
});

