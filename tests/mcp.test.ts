describe('no stale /mcp literal survives item 1’s endpoint departure (MO-2)', () => {
  /** Every file under `dir`, any extension — unlike `listSourceFiles`, this is
   *  not limited to `.ts`: `templates/mcp/README.md`'s published literal (a
   *  Markdown backtick span, not a JS/TS quoted string) must be swept too. */
  async function listAllFiles(dir: string): Promise<string[]> {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    const files: string[] = [];
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        files.push(...(await listAllFiles(full)));
      } else if (entry.isFile()) {
        files.push(full);
      }
    }
    return files;
  }

  it('the pre-departure endpoint occurs zero times under src/ and zero times under templates/, checked end-anchored so the new URL (which contains the old one as a prefix) can never false-positive-pass', async () => {
    // End-anchored, not a bare substring: matches "…/mcp" only when nothing
    // extends the path further (no following "/", word character or "-").
    // "https://mcp.context7.com/mcp/oauth" therefore never matches this
    // pattern, because "/oauth" follows — MO-2's whole point.
    const OLD_ENDPOINT_END_ANCHORED = /https:\/\/mcp\.context7\.com\/mcp(?![\/\w-])/g;

    const srcFiles = await listAllFiles(path.join(REPO_ROOT, 'src'));
    const templateFiles = await listAllFiles(path.join(REPO_ROOT, 'templates'));

    for (const file of [...srcFiles, ...templateFiles]) {
      const contents = await fs.readFile(file, 'utf8');
      const matches = contents.match(OLD_ENDPOINT_END_ANCHORED) ?? [];
      expect(
        matches.length,
        `${path.relative(REPO_ROOT, file)} still contains the pre-departure /mcp endpoint literal`,
      ).toBe(0);
    }
  });
});
