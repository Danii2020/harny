describe('buildMcpFiles — ordering, skip behavior, and merge-marking', () => {
  function fakeGenerator(id: string, mcpConfig: unknown) {
    return { id, mcpConfig } as any;
  }

  it('contributes nothing for a generator whose mcpConfig is undefined, and preserves generator order for both files and warnings', async () => {
    const { buildMcpFiles } = await import('../src/mcp.js');
    const targetDir = await makeTempDir();

    // x3 pre-seeded already-present (unchanged, warns); x4 pre-seeded unparseable
    // (skipped, warns) -- in generator order, before the two fresh writes.
    await fs.mkdir(path.join(targetDir, 'b'), { recursive: true });
    await fs.writeFile(path.join(targetDir, 'b', 'config.toml'), '[mcp_servers.context7]\nurl = "x"\n');
    await fs.mkdir(path.join(targetDir, 'c'), { recursive: true });
    await fs.writeFile(path.join(targetDir, 'c', 'mcp.json'), '{ not valid json');

    const generators = [
      fakeGenerator('x1', undefined),
      fakeGenerator('x2', { path: 'a/mcp.json', format: 'json', rootKey: 'mcpServers', entry: { url: 'https://mcp.context7.com/mcp/oauth' } }),
      fakeGenerator('x3', { path: 'b/config.toml', format: 'toml', rootKey: 'mcp_servers', entry: { url: 'https://mcp.context7.com/mcp/oauth' } }),
      fakeGenerator('x4', { path: 'c/mcp.json', format: 'json', rootKey: 'mcpServers', entry: { url: 'https://mcp.context7.com/mcp/oauth' } }),
      fakeGenerator('x5', { path: 'd/mcp.json', format: 'json', rootKey: 'mcpServers', entry: { url: 'https://mcp.context7.com/mcp/oauth' } }),
    ];

    const result = await buildMcpFiles(generators, { targetDir, force: false });

    expect(result.files.map((f) => f.path)).toEqual(['a/mcp.json', 'd/mcp.json']);
    for (const file of result.files) {
      expect((file as { merge?: true }).merge).toBe(true);
    }

    expect(result.warnings).toHaveLength(2);
    expect(result.warnings[0]).toContain('b/config.toml');
    expect(result.warnings[1]).toContain('c/mcp.json');

    // buildMcpFiles only reads and returns data; it is never the thing that
    // actually writes to disk (that is applyWrites, driven by the caller).
    await expect(fs.access(path.join(targetDir, 'a', 'mcp.json'))).rejects.toThrow();
    await expect(fs.access(path.join(targetDir, 'd', 'mcp.json'))).rejects.toThrow();
  });

  it('treats a missing parent directory the same as any other absent file: writes fresh content', async () => {
    const { buildMcpFiles } = await import('../src/mcp.js');
    const targetDir = await makeTempDir();

    const generators = [
      fakeGenerator('x1', {
        path: 'nested/deep/mcp.json',
        format: 'json',
        rootKey: 'mcpServers',
        entry: { url: 'https://mcp.context7.com/mcp/oauth' },
      }),
    ];

    const result = await buildMcpFiles(generators, { targetDir, force: false });

    expect(result.files).toHaveLength(1);
    expect(result.files[0].path).toBe('nested/deep/mcp.json');
    expect(result.warnings).toHaveLength(0);
  });

  it('treats a non-ENOENT filesystem read error as skipped-with-warning, never as absent and never as a thrown error', async () => {
    const { buildMcpFiles } = await import('../src/mcp.js');
    const targetDir = await makeTempDir();

    // A directory sitting at the exact path the config expects a file: reading
    // it raises EISDIR, not ENOENT.
    await fs.mkdir(path.join(targetDir, 'weird', 'mcp.json'), { recursive: true });

    const generators = [
      fakeGenerator('x1', {
        path: 'weird/mcp.json',
        format: 'json',
        rootKey: 'mcpServers',
        entry: { url: 'https://mcp.context7.com/mcp/oauth' },
      }),
    ];

    const result = await buildMcpFiles(generators, { targetDir, force: false });

    expect(result.files).toHaveLength(0);
    expect(result.warnings).toHaveLength(1);
    expect(result.warnings[0]).toContain('weird/mcp.json');
  });
});

